/**
  ******************************************************************************
  * @file    mpu6500.h
  * @brief   MPU6500 六轴惯性测量单元（三轴加速度 + 三轴陀螺仪）驱动接口。
  *
  *          本文件是驱动的「业务层」接口，对外只暴露物理量：
  *          加速度以 g 为单位、角速度以 °/s 为单位、温度以 ℃ 为单位，
  *          调用者无需了解 I2C 寄存器与原始数据格式。
  *
  *          底层实现分两层：
  *            - Src/mpu6500.c      ：本层，负责量程/采样率配置与原始数据换算。
  *            - Src/mpu6500_port.c ：移植层，负责 I2C1 时序与毫秒时基。
  *          两者之间通过 InvenSense 官方库 Lib/InvenSense/inv_mpu.c 衔接。
  ******************************************************************************
  */

#ifndef MPU6500_H
#define MPU6500_H

#include <stdint.h>

/**
  * @brief  一次完整采样的结果，各成员单位已换算为物理量。
  *
  * @note   为保持结构体赋值时的原子性，驱动内部先填满一个临时变量再整体拷贝，
  *         因此调用者读到的三轴数据来自同一次 I2C 采样。
  */
typedef struct
{
    float accel_g[3];       /*!< 三轴加速度，单位 g，下标 0/1/2 依次对应 X/Y/Z 轴。 */
    float gyro_dps[3];      /*!< 三轴角速度，单位 °/s，下标 0/1/2 依次对应 X/Y/Z 轴。 */
    float temperature_c;    /*!< 芯片内部温度，单位 ℃。 */
    uint32_t timestamp_ms;  /*!< 采样时刻的毫秒时基，来自 SysTick 计数器。 */
} Mpu6500_Data;

/**
  * @brief  初始化 MPU6500。
  *
  *         依次完成：移植层初始化（SysTick 时基、GPIO、I2C1）、芯片复位与唤醒、
  *         使能加速度计与陀螺仪、配置量程/采样率/低通滤波器、读取灵敏度系数。
  *         其中陀螺仪量程为 ±500 dps，加速度计量程为 ±4 g，采样率 1 kHz，
  *         数字低通滤波器带宽 98 Hz。
  *
  * @param  无
  * @retval  0  初始化成功
  * @retval -1  移植层初始化失败（通常是 SysTick 配置失败）
  * @retval -2  芯片无应答，mpu_init 失败（检查供电、PB6/PB7 接线与上拉电阻、
  *             AD0 引脚电平决定的从机地址 0x68/0x69）
  * @retval -3  寄存器配置失败（某一项量程/采样率/滤波器设置被拒绝）
  *
  * @note   初始化失败后内部状态被复位为「未初始化」，
  *         此后所有 Mpu6500_Read 调用都会直接返回 -1。
  */
int Mpu6500_Init(void);

/**
  * @brief  读取一次加速度、角速度与温度。
  *
  *         一次调用会顺序发起 3 次 I2C 传输：陀螺仪 6 字节、加速度计 6 字节、
  *         温度 2 字节，然后按初始化时取得的灵敏度系数换算为物理量。
  *
  * @param[out] data  采样结果输出缓冲，不可为 NULL。
  * @retval  0  读取成功，data 已被填充
  * @retval -1  参数无效（data 为 NULL）或驱动尚未初始化
  * @retval -2  I2C 传输失败（总线无应答、仲裁丢失等，移植层已尝试恢复总线）
  *
  * @note   本函数内含阻塞等待，单次调用耗时与 I2C 速率相关；
  *         在 400 kHz 下约 0.5 ms 量级。若需严格定时采样，
  *         请自行按 timestamp_ms 判断采样间隔，或改由定时器中断触发。
  */
int Mpu6500_Read(Mpu6500_Data *data);

#endif /* MPU6500_H */
